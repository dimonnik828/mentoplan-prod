async function updateCategories() {
  console.log('🔄 Обновление категорий...');
  const all = await prisma.tTK.findMany();

  for (const ttk of all) {
    const newCategory = getCategory(ttk.title, ttk.type);
    await prisma.tTK.update({
      where: { id: ttk.id },
      data: { category: newCategory },
    });
  }

  console.log(`✅ Обновлены категории для ${all.length} записей`);
}

updateCategories()
  .catch((e) => {
    console.error('❌ Ошибка:', e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());